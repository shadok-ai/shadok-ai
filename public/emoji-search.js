/**
 * Does this string already contain a real emoji? Then it is a literal icon the
 * user typed, not a word to search for.
 */
export function looksLikeEmoji(s) {
  try {
    return /\p{Extended_Pictographic}/u.test(String(s ?? ""));
  } catch {
    // A runtime without Unicode property escapes: fall back to "any non-ASCII".
    return /[^\u0000-ÿ]/.test(String(s ?? ""));
  }
}

/**
 * Emojis whose keywords match the query, best first. Ranking per emoji is the
 * strongest match over the query's tokens: a keyword equal to a token (3) beats
 * one that starts with it (2), which beats one that merely contains it (1).
 * Deduped and capped at `limit`. An empty or whitespace query returns [].
 */
export function searchEmoji(query, limit = 24) {
  const q = String(query ?? "").toLowerCase().trim();
  if (!q) return [];
  const tokens = q.split(/\s+/).filter(Boolean);
  const scored = [];
  for (const [emoji, kw] of EMOJI) {
    const words = kw.split(/\s+/);
    let best = 0;
    for (const t of tokens) {
      for (const w of words) {
        if (w === t) best = Math.max(best, 3);
        else if (w.startsWith(t)) best = Math.max(best, 2);
        else if (t.length >= 2 && w.includes(t)) best = Math.max(best, 1);
      }
    }
    if (best) scored.push([emoji, best]);
  }
  scored.sort((a, b) => b[1] - a[1]);
  const seen = new Set();
  const out = [];
  for (const [e] of scored) {
    if (seen.has(e)) continue;
    seen.add(e);
    out.push(e);
    if (out.length >= limit) break;
  }
  return out;
}
